function createPlaylistArtworkPath(region: string) {
  return `/assets/playlists/${region}.webp`;
}

function createMusicSearchTrack(input: {
  artist: string;
  fallbackColor: string;
  id: string;
  title: string;
}) {
  const query = encodeURIComponent(`${input.artist} ${input.title}`);
  const searchUrl = `https://music.youtube.com/search?q=${query}`;

  return {
    ...input,
    externalUrl: searchUrl,
    platformUrls: {
      youtubeMusic: searchUrl,
    } satisfies Prisma.JsonObject,
  };
}

